#!/usr/bin/env bash
#
# Start the pgauthz stack (PostgreSQL + pgauthzd). OPA is OPT-IN (--opa).
# Builds images if needed. Waits until all services are healthy.
#
# Options:
#   --cel       Build the Postgres image with the pg_cel extension (CEL
#               conditions). Equivalent to PGAUTHZ_CEL=1; run ./init.sh after.
#   --opa       Add the OPA policy sidecar + the OPA-fronted pgauthzd gateway
#               (compose-opa.yml). The default stack is OPA-free (direct pgx).
#   --keycloak  Also start the demo Keycloak OIDC issuer (compose-keycloak.yml);
#               implies --opa. Run ./keycloak/config/generate-mkcerts.sh first
#               to create the *.pgauthz.test TLS certs.
#   --playground  Also start the playground (Lit SPA + Go BFF) at
#                 https://app.pgauthz.test. Implies --keycloak; run terraform
#                 apply afterwards to provision the playground-bff client.
#   --console   Also start the management console (Lit SPA + Go BFF) at
#               https://app.pgauthz.test/console/. Implies --keycloak; run
#               terraform apply afterwards to provision the console-bff client.
#   --console-local  The console WITHOUT Keycloak at http://localhost:8095/console/
#               (compose-console-local.yml): local admin sign-in admin / admin
#               (CONSOLE_LOCAL_ADMIN_PASSWORD), no proxy, no OPA. For a quick
#               look at the console itself; not combinable with --console.
#   --metrics   Also start Prometheus + Grafana scraping the pgauthzd /metrics
#               (compose-metrics.yml). UIs: :9095 (Prometheus) / :9096 (Grafana).
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

OPA=0
KEYCLOAK=0
PLAYGROUND=0
CONSOLE=0
CONSOLE_LOCAL=0
METRICS=0
for arg in "$@"; do
  case "$arg" in
    --cel)        export PGAUTHZ_CEL=1 ;;
    --opa)        OPA=1 ;;
    --keycloak)   KEYCLOAK=1 ;;
    --playground) PLAYGROUND=1 ;;
    --console)    CONSOLE=1 ;;
    --console-local) CONSOLE_LOCAL=1 ;;
    --metrics)    METRICS=1 ;;
    -h|--help)    sed -n '2,26p' "$0"; exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done
# The playground depends on keycloak; keycloak routes through the OPA overlay.
if [ "$PLAYGROUND" = 1 ] || [ "$CONSOLE" = 1 ]; then KEYCLOAK=1; fi
if [ "$CONSOLE" = 1 ] && [ "$CONSOLE_LOCAL" = 1 ]; then
  echo "==> --console and --console-local both define the console; keeping --console (Keycloak)"
  CONSOLE_LOCAL=0
fi
if [ "$KEYCLOAK" = 1 ]; then OPA=1; fi

# Persist the overlay selection so env.sh (sourced by init.sh, test.sh,
# reload-engine.sh, ...) operates on the SAME stack: without this, any of
# those scripts recreates opa/pgauthzd-opa from the base compose files and
# silently drops the keycloak/playground env (issuers, REQUIRE_TOKEN_FOR_READS,
# FORWARD_TOKEN_TO_OPA, ...). Overwritten on every start, so a plain ./start.sh
# clears it. Explicit env vars still override (the :- guards below).
{
  echo "# generated by start.sh — the overlays of the currently running stack"
  echo "# (env.sh sources this; explicit PGAUTHZ_* env vars take precedence)"
  echo "export PGAUTHZ_CEL=\"\${PGAUTHZ_CEL:-${PGAUTHZ_CEL:-0}}\""
  echo "export PGAUTHZ_OPA=\"\${PGAUTHZ_OPA:-$OPA}\""
  echo "export PGAUTHZ_KEYCLOAK=\"\${PGAUTHZ_KEYCLOAK:-$KEYCLOAK}\""
  echo "export PGAUTHZ_PLAYGROUND=\"\${PGAUTHZ_PLAYGROUND:-$PLAYGROUND}\""
  echo "export PGAUTHZ_CONSOLE=\"\${PGAUTHZ_CONSOLE:-$CONSOLE}\""
  echo "export PGAUTHZ_CONSOLE_LOCAL=\"\${PGAUTHZ_CONSOLE_LOCAL:-$CONSOLE_LOCAL}\""
  echo "export PGAUTHZ_METRICS=\"\${PGAUTHZ_METRICS:-$METRICS}\""
} > "$SCRIPT_DIR/.pgauthz-overlays"

# Compose files — base stack + optional authzen overlay
COMPOSE_FILES=(-f "$SCRIPT_DIR/compose.yml")
if [ -f "$SCRIPT_DIR/compose-authzen.yml" ]; then
  COMPOSE_FILES+=(-f "$SCRIPT_DIR/compose-authzen.yml")
fi

# Optional CEL overlay (see env.sh / extensions/pg-cel).
case "${PGAUTHZ_CEL:-}" in
  1|true|yes|on)
    COMPOSE_FILES+=(-f "$SCRIPT_DIR/compose-cel.yml")
    echo "==> CEL enabled (building pg_cel into the Postgres image)"
    ;;
esac

# Optional OPA overlay (policy-as-code). Must precede keycloak/playground — it
# DEFINES pgauthzd-opa, which those overlays override.
if [ "$OPA" = 1 ]; then
  COMPOSE_FILES+=(-f "$SCRIPT_DIR/compose-opa.yml")
  echo "==> OPA enabled (compose-opa.yml: OPA sidecar + OPA-fronted gateway)"
fi

# Optional Keycloak demo issuer overlay (see keycloak/README.md).
if [ "$KEYCLOAK" = 1 ]; then
  certs="$SCRIPT_DIR/keycloak/config/certs"
  if [ ! -s "$certs/cert.pem" ] || [ ! -s "$certs/key.pem" ] || [ ! -s "$certs/rootCA.pem" ]; then
    echo "!! --keycloak needs TLS certs that don't exist yet." >&2
    echo "   Run ./keycloak/config/generate-mkcerts.sh first (it runs 'mkcert -install')." >&2
    exit 1
  fi
  COMPOSE_FILES+=(-f "$SCRIPT_DIR/compose-keycloak.yml")
  echo "==> Keycloak demo issuer enabled (compose-keycloak.yml)"
fi

# Optional playground overlay (Lit SPA + Go BFF; needs the keycloak overlay).
if [ "$PLAYGROUND" = 1 ]; then
  COMPOSE_FILES+=(-f "$SCRIPT_DIR/compose-playground.yml")
  echo "==> Playground enabled (compose-playground.yml)"
fi

# Optional console overlay (management console: Lit SPA + Go BFF; needs keycloak).
if [ "$CONSOLE" = 1 ]; then
  COMPOSE_FILES+=(-f "$SCRIPT_DIR/compose-console.yml")
  echo "==> Console enabled (compose-console.yml)"
fi

# Optional Keycloak-free console overlay (local admin sign-in, host port).
if [ "$CONSOLE_LOCAL" = 1 ]; then
  COMPOSE_FILES+=(-f "$SCRIPT_DIR/compose-console-local.yml")
  echo "==> Console enabled without Keycloak (compose-console-local.yml)"
fi

# Optional metrics overlay (Prometheus + Grafana scraping pgauthzd /metrics).
if [ "$METRICS" = 1 ]; then
  COMPOSE_FILES+=(-f "$SCRIPT_DIR/compose-metrics.yml")
  echo "==> Metrics enabled (compose-metrics.yml: Prometheus + Grafana)"
fi

# Git revision for the console footer (compose-console.yml build arg).
export REVISION="${REVISION:-$(git -C "$SCRIPT_DIR" rev-parse --short=12 HEAD 2>/dev/null || true)}"

echo "==> Starting pgauthz stack..."
docker compose "${COMPOSE_FILES[@]}" up -d --build --wait

echo "==> Stack is running."
docker compose "${COMPOSE_FILES[@]}" ps

if [ "$CONSOLE" = 1 ] || [ "$CONSOLE_LOCAL" = 1 ]; then
  # The console's own store: created once from the example model + seed when
  # the engine is installed and the store is missing (never reset afterwards;
  # test.sh uses its own copy, console_test).
  db_psql() { docker compose "${COMPOSE_FILES[@]}" exec -T -e PGPASSWORD="${PG_PASSWORD:-authz}" "${DB_SERVICE:-authz-db}" psql -v ON_ERROR_STOP=1 -U "${PG_USER:-authz}" -d "${PG_DB:-authz}" "$@"; }
  if db_psql -Atc "SELECT 1 FROM authz.stores LIMIT 1" >/dev/null 2>&1; then
    if [ "$(db_psql -Atc "SELECT count(*) FROM authz.stores WHERE name = 'console'")" = "0" ]; then
      echo "==> Creating the console store (examples/models/console: model + seed)"
      db_psql -q < "$SCRIPT_DIR/examples/models/console/model.sql" >/dev/null
      db_psql -q < "$SCRIPT_DIR/examples/models/console/seed.sql" >/dev/null
    fi
  else
    echo "==> Console store not created yet: run ./init.sh, then ./start.sh --console again"
  fi
  echo ""
  if [ "$CONSOLE_LOCAL" = 1 ]; then
    echo "==> Console: http://localhost:${CONSOLE_LOCAL_PORT:-8095}/console/  (local admin: ${CONSOLE_LOCAL_ADMIN_USER:-admin} / ${CONSOLE_LOCAL_ADMIN_PASSWORD:-admin})"
  else
    echo "==> Console: https://app.pgauthz.test/console/  (console-bff client: terraform apply)"
  fi
fi

if [ "$KEYCLOAK" = 1 ]; then
  echo ""
  echo "==> Keycloak issuer: https://id.pgauthz.test   admin: https://admin.pgauthz.test"
  echo "    Provision realm:  (cd keycloak/terraform && terraform init && terraform apply)"
  echo "    Get a token:      eval \"\$(./keycloak/get-token.sh bob)\""
fi

if [ "$METRICS" = 1 ]; then
  echo ""
  echo "==> Prometheus: http://localhost:9095   Grafana: http://localhost:9096 (anonymous admin)"
fi

if [ "$PLAYGROUND" = 1 ]; then
  echo ""
  echo "==> Playground: https://app.pgauthz.test  (add app.pgauthz.test to /etc/hosts)"
  echo "    Provision the BFF client first: (cd keycloak/terraform && terraform apply)"
fi
